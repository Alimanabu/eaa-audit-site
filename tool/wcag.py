BY_ID = {c[0]: c for c in CRITERIA}
AXE_TAGS = ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]
_SC = re.compile(r"^wcag(\d)(\d)(\d{1,2})$")
IMPACT_ORDER = {"critical": 4, "serious": 3, "moderate": 2, "minor": 1, None: 0}


def criteria_from_tags(tags):
    """axe tags like wcag143, wcag1412 -> WCAG 2.1 ids; 2.2-only criteria are dropped."""
    out = []
    for tag in tags:
        m = _SC.match(tag)
        if m:
            sc = ".".join(m.groups())
            if sc in BY_ID and sc not in out:
                out.append(sc)
    return out


def level_from_tags(tags):
    return "AA" if {"wcag2aa", "wcag21aa"} & set(tags) else "A"


